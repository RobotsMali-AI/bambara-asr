import json
from typing import List, Optional, Callable, Tuple

import torch
from torch.utils.data import Dataset, DataLoader
from torch.nn.utils.rnn import pad_sequence
import torchaudio
from sentencepiece import SentencePieceProcessor

TOKENIZER_PAD_ID = 1 # valid for this tokenizer (we might need to change if we retrain it)

def load_sentencepiece_tokenizer(model_path: str) -> SentencePieceProcessor:
    """
    Utility to load a SentencePiece tokenizer.

    Args:
        model_path (str): Path to the .model file generated by SentencePiece.

    Returns:
        SentencePieceProcessor: Initialized tokenizer.
    """
    sp = SentencePieceProcessor()
    sp.Load(model_path)
    return sp


class RewardDataset(Dataset):
    """
    PyTorch Dataset for loading audio, text, and human-score samples
    for a reward model.

    Each item is a tuple: (audio_feat, text_ids, score)
      - audio_feat: torch.Tensor, shape [N_mel, T]
      - text_ids: List[int], token IDs of transcription
      - score: float, normalized between 0 and 1
    """

    def __init__(
        self,
        manifest_path: str,
        tokenizer_model_path: str,
        preprocessor: torch.nn.Module,
        device: torch.device,
        sample_rate: Optional[int] = 16000,
        audio_transform: Optional[Callable] = None,
    ):
        """
        Args:
            manifest_path (str): Path to the .jsonl manifest file.
            tokenizer_model_path (str): Path to SentencePiece .model file.
            preprocessor (torch.nn.Module): Pretrained QuartzNet audio preprocessor.
            sample_rate (int, optional): If provided, resample audio to this rate.
            audio_transform (Callable, optional): Additional audio transforms.
        """
        self.preprocessor = preprocessor
        # Ensure the preprocessor is on the same device as the input Tensors
        # In order to avoid RuntimeError: stft input and window must be on the same device
        self.preprocessor.to(device)
        self.sample_rate = sample_rate
        self.audio_transform = audio_transform

        # Load tokenizer
        self.tokenizer = load_sentencepiece_tokenizer(tokenizer_model_path)

        # Read manifest into memory
        self.samples = []
        with open(manifest_path, "r", encoding="utf-8") as f:
            for line in f:
                data = json.loads(line)
                # Ensure required keys
                assert all(k in data for k in ("audio_filepath", "transcription", "score")), \
                    f"Manifest line missing keys: {data}"
                self.samples.append(data)

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        record = self.samples[idx]

        # ----- Audio preprocessing -----
        waveform, sr = torchaudio.load(record["audio_filepath"])
        # Optional resampling
        if self.sample_rate is not None and sr != self.sample_rate:
            resampler = torchaudio.transforms.Resample(sr, self.sample_rate)
            waveform = resampler(waveform)
            sr = self.sample_rate
        
        length_tensor = torch.tensor([waveform.size(1)], dtype=torch.long)

        # Ensure batch dimension: [batch, ...] (Not necessary)
        # audio_batch = waveform
        # if audio_batch.dim() == 1:
        #     audio_batch = audio_batch.unsqueeze(0)
        # elif audio_batch.dim() == 2:
        #     audio_batch = audio_batch.unsqueeze(0)

        # Apply QuartzNet preprocessor -> [1, N_mel, T]
        feats, _ = self.preprocessor(input_signal=waveform, length=length_tensor)

        # Remove batch dim -> [N_mel, T]
        audio_feat = feats.squeeze(0)

        # Additional audio transforms
        if self.audio_transform is not None:
            audio_feat = self.audio_transform(audio_feat)

        # ----- Text preprocessing -----
        text = record["transcription"]
        text_ids: List[int] = self.tokenizer.EncodeAsIds(text)

        # Ensure text_ids for empty strings will not be empty, instead they will contain the pad_id
        if len(text_ids) == 0:
            text_ids = [TOKENIZER_PAD_ID]

        # ----- Score normalization -----
        score: float = float(record["score"]) / 100.0

        return audio_feat, text_ids, score

def reward_collate_fn(batch):
    """
    Collate function to batch variable-length audio and text data.

    Args:
        batch: List of tuples (audio_feat, text_ids, score).

    Returns:
        dict with:
            audio_batch: Tensor [B, N_mel, max_T]
            audio_lengths: Tensor [B]
            text_batch: Tensor [B, max_seq_len]
            text_lengths: Tensor [B]
            score_batch: Tensor [B]
    """
    # Unzip batch
    audio_feats, text_id_lists, scores = zip(*batch)

    # Audio padding
    mel_bins = audio_feats[0].size(0)
    lengths = [feat.size(1) for feat in audio_feats]
    max_length = max(lengths)
    audio_batch = torch.zeros(len(batch), mel_bins, max_length)
    for i, feat in enumerate(audio_feats):
        audio_batch[i, :, :feat.size(1)] = feat
    audio_lengths = torch.tensor(lengths, dtype=torch.long)

    # Text padding
    text_tensors = [torch.tensor(ids, dtype=torch.long) for ids in text_id_lists]
    text_batch = pad_sequence(text_tensors, batch_first=True, padding_value=TOKENIZER_PAD_ID)
    text_lengths = torch.tensor([t.size(0) for t in text_tensors], dtype=torch.long)

    # Score tensor
    score_batch = torch.tensor(scores, dtype=torch.float)

    return {
        "audio_batch": audio_batch,
        "audio_lengths": audio_lengths,
        "text_batch": text_batch,
        "text_lengths": text_lengths,
        "score_batch": score_batch,
    }


def get_dataloaders(
    train_manifest: str,
    test_manifest: str,
    tokenizer_model_path: str,
    preprocessor: torch.nn.Module,
    batch_size: int,
    device: torch.device,
    sample_rate: Optional[int] = 16000,
    audio_transform: Optional[Callable] = None,
    num_workers: int = 0,
) -> Tuple[DataLoader, DataLoader]:
    """
    Utility to create DataLoaders for training and testing.

    Args:
        train_manifest (str): Path to training manifest .jsonl.
        test_manifest (str): Path to testing manifest .jsonl.
        tokenizer_model_path (str): Path to SentencePiece .model file.
        preprocessor (torch.nn.Module): Pretrained QuartzNet preprocessor.
        batch_size (int): Batch size.
        sample_rate (int, optional): Desired audio sample rate.
        audio_transform (Callable, optional): Additional audio transforms.
        num_workers (int): Number of worker processes.

    Returns:
        train_loader, test_loader: DataLoader objects.
    """
    train_ds = RewardDataset(
        train_manifest,
        tokenizer_model_path,
        preprocessor,
        device,
        sample_rate,
        audio_transform,
    )

    test_ds = RewardDataset(
        test_manifest,
        tokenizer_model_path,
        preprocessor,
        device,
        sample_rate,
        audio_transform,
    )

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=True,
        collate_fn=reward_collate_fn,
        num_workers=num_workers,
    )
    test_loader = DataLoader(
        test_ds,
        batch_size=batch_size,
        shuffle=False,
        collate_fn=reward_collate_fn,
        num_workers=num_workers,
    )
    return train_loader, test_loader
